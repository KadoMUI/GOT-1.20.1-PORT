    private final List<Region> regions;
    private final String factionCode;
    private final double imgX;
    private final double imgY;
    private final int coordX;
    private final int coordZ;
    private boolean hidden;

    GOTWaypoint(List<Region> regions, String factionCode, double imgX, double imgY, boolean hidden) {
        this.regions = List.copyOf(regions);
        this.factionCode = factionCode;
        this.imgX = imgX;
        this.imgY = imgY;
        this.coordX = mapToWorldX(imgX);
        this.coordZ = mapToWorldZ(imgY);
        this.hidden = hidden;
        for (Region region : regions) region.waypoints.add(this);
    }

    public static List<GOTAbstractWaypoint> listAllWaypoints() { return new ArrayList<>(List.of(values())); }
    public static int mapToWorldR(double r) { return (int)Math.round(r * 128.0D); }
    public static int mapToWorldX(double x) { return (int)Math.round((x - 653.0D + 0.5D) * 128.0D); }
    public static int mapToWorldZ(double z) { return (int)Math.round((z - 870.0D + 0.5D) * 128.0D); }
    public static int worldToMapR(double r) { return (int)Math.round(r / 128.0D); }
    public static int worldToMapX(double x) { return (int)Math.round(x / 128.0D + 653.0D - 0.5D); }
    public static int worldToMapZ(double z) { return (int)Math.round(z / 128.0D + 870.0D - 0.5D); }

    public static Region regionForID(int id) {
        Region[] all = Region.values();
        return id >= 0 && id < all.length ? all[id] : null;
    }
    public static Region regionForName(String name) {
        if (name == null) return null;
        for (Region r : Region.values()) if (r.name().equalsIgnoreCase(name)) return r;
        return null;
    }
    public static GOTWaypoint byId(int id) {
        GOTWaypoint[] all = values();
        return id >= 0 && id < all.length ? all[id] : null;
    }

    public static GOTWaypoint waypointForName(String name) {
        if (name == null) return null;
        for (GOTWaypoint w : values()) {
            if (w.name().equalsIgnoreCase(name) || w.getDisplayName().getString().equalsIgnoreCase(name)) return w;
        }
        return null;
    }

